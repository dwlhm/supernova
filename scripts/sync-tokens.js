const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const sourceTokensDir = path.join(rootDir, 'output', 'tokens');
const targetTokensDir = path.join(rootDir, 'packages', 'tokens');
const targetSrcDir = path.join(targetTokensDir, 'src');
const targetCssDir = path.join(targetTokensDir, 'css');

function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function copyFileIfExists(src, dest) {
  if (fs.existsSync(src)) {
    fs.copyFileSync(src, dest);
    console.log(`Copied ${path.relative(rootDir, src)} -> ${path.relative(rootDir, dest)}`);
    return true;
  } else {
    console.warn(`Source file not found: ${src}`);
    return false;
  }
}

function syncTokens() {
  console.log('--- Syncing Tokens ---');
  ensureDir(targetSrcDir);
  ensureDir(targetCssDir);

  // Sync TS tokens
  const srcTs = path.join(sourceTokensDir, 'tokens.ts');
  const destTs = path.join(targetSrcDir, 'tokens.ts');
  copyFileIfExists(srcTs, destTs);

  // Sync CSS tokens
  const srcCss = path.join(sourceTokensDir, 'tokens.css');
  const destCss = path.join(targetCssDir, 'tokens.css');
  copyFileIfExists(srcCss, destCss);

  const srcTheme = path.join(sourceTokensDir, 'theme.css');
  const destTheme = path.join(targetCssDir, 'theme.css');
  copyFileIfExists(srcTheme, destTheme);

  // Generate packages/tokens/src/index.ts
  const indexTsContent = `// Auto-generated by sync-tokens script. Do not edit directly.
export * from './tokens';
export { default } from './tokens';
`;
  const destIndexTs = path.join(targetSrcDir, 'index.ts');
  fs.writeFileSync(destIndexTs, indexTsContent, 'utf-8');
  console.log(`Generated ${path.relative(rootDir, destIndexTs)}`);

  console.log('Tokens synced successfully!\n');
}

syncTokens();
