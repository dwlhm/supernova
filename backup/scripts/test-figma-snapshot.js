const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { cacheFigmaFile, loadSnapshot, discoverSnapshotComponents, resolveSnapshotNode } = require('./figma-snapshot');
const { importFigmaComponents } = require('./import-figma-components');
const { processPrComponents, resolveFigmaNode } = require('./process-pr-components');
const root = path.resolve(__dirname, '..');
const temp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'figma-snapshot-')));
const fileKey = 'snapshot-test-file';
const load = name => JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures', name), 'utf8'));
const breadcrumb = load('breadcrumb.figma.json');
breadcrumb.type = 'COMPONENT';
const set = { id: 'set', name: 'Breadcrumb', type: 'COMPONENT_SET', componentPropertyDefinitions: breadcrumb.componentPropertyDefinitions, children: [breadcrumb] };
const legacy = { id: 'legacy', type: 'COMPONENT', name: 'Legacy', children: [] };
const file = { document: { id: 'document', type: 'DOCUMENT', children: [{ id: 'snapshot-page', name: 'Components', type: 'CANVAS', children: [set, legacy] }] }, version: 'fixture-version', lastModified: '2026-10-06T00:00:00Z', components: { breadcrumb: { key: 'breadcrumb-key', componentSetId: 'set' } }, componentSets: { set: { key: 'set-key' } } };
const cachePath = path.join(temp, 'snapshot.json');
(async () => {
  const previousCwd = process.cwd();
  try {
    let requests = 0;
    const fetchFn = async (url, options) => {
      requests++;
      assert(url.endsWith('?geometry=paths') && !url.includes('depth='));
      assert.strictEqual(options.headers['X-Figma-Token'], 'test-token-never-persist');
      return { ok: true, json: async () => file };
    };
    let result = await cacheFigmaFile({ fileKey, token: 'test-token-never-persist', out: cachePath, fetchFn });
    assert.strictEqual(requests, 1);
    assert(!result.reused);
    assert(!fs.readFileSync(cachePath, 'utf8').includes('test-token-never-persist'));
    result = await cacheFigmaFile({ fileKey, out: cachePath, fetchFn: () => { throw new Error('Network forbidden for cache reuse'); } });
    assert(result.reused && requests === 1);
    assert.strictEqual(result.snapshot.file.version, file.version);
    assert.strictEqual(resolveSnapshotNode(result.snapshot, 'separator').id, 'separator');
    assert.throws(() => resolveSnapshotNode(result.snapshot, 'missing'), /absent/);
    assert.throws(() => resolveSnapshotNode(result.snapshot, 'separator', 'different-file'), /does not match/);
    const originalCache = fs.readFileSync(cachePath, 'utf8');
    await assert.rejects(cacheFigmaFile({ fileKey, token: 'secret', out: cachePath, refresh: true, fetchFn: async () => ({ ok: false, status: 403 }) }), /HTTP 403/);
    assert.strictEqual(fs.readFileSync(cachePath, 'utf8'), originalCache);
    await assert.rejects(cacheFigmaFile({ fileKey, token: 'secret', out: cachePath, refresh: true, fetchFn: async () => ({ ok: true, json: async () => ({ err: 'not a file' }) }) }), /Invalid Figma snapshot/);
    assert.strictEqual(fs.readFileSync(cachePath, 'utf8'), originalCache);
    const invalidPath = path.join(temp, 'invalid.json');
    fs.writeFileSync(invalidPath, '{}');
    await assert.rejects(cacheFigmaFile({ fileKey, out: invalidPath, fetchFn: () => { throw new Error('No network on invalid cache'); } }), /Invalid Figma snapshot/);
    assert.throws(() => loadSnapshot(invalidPath), /Invalid Figma snapshot/);
    assert(!fs.readdirSync(temp).some(name => name.endsWith('.tmp')));

    const discovered = discoverSnapshotComponents(result.snapshot);
    assert.strictEqual(discovered.length, 2, 'Variants are not independent standalone components');
    assert.strictEqual(discovered[0].node_id, 'set');
    assert.strictEqual(discovered[0].key, 'set-key');
    assert.deepStrictEqual(discovered[0].componentPropertyDefinitions, set.componentPropertyDefinitions);
    assert.strictEqual(discovered[0].variants[0].id, 'breadcrumb');
    const catalogPath = path.join(temp, 'components.catalog.json');
    const imported = await importFigmaComponents({ figmaSnapshot: cachePath, out: catalogPath, merge: false, only: 'Breadcrumb', silent: true, fetchFn: () => { throw new Error('Offline import forbids network'); } });
    assert.strictEqual(imported.catalog[0].nodeId, 'set');
    assert.deepStrictEqual(imported.catalog[0].componentPropertyDefinitions, set.componentPropertyDefinitions);
    const resolved = await resolveFigmaNode({ name: 'Breadcrumb', nodeId: 'set', fileId: fileKey }, { snapshot: result.snapshot, fixturesDir: path.join(__dirname, 'fixtures') });
    assert.strictEqual(resolved.id, 'set', 'Actual snapshot beats local example fixture');
    process.chdir(temp);
    fs.writeFileSync('components.composition.json', JSON.stringify({ Breadcrumb: load('breadcrumb.composition.json') }));
    let processed = await processPrComponents({ figmaSnapshot: cachePath, catalog: catalogPath, silent: true, token: 'present-but-offline' });
    assert.strictEqual(processed.summary.failed, 0);
    assert.strictEqual(processed.manifest.components.Breadcrumb.outputs.length, 7);
    assert.strictEqual(processed.manifest.components.Breadcrumb.snapshot.version, file.version);
    assert(!fs.readFileSync('components/Breadcrumb.lite.tsx', 'utf8').includes('props.type'));
    processed = await processPrComponents({ figmaSnapshot: cachePath, catalog: catalogPath, silent: true });
    assert.strictEqual(processed.summary.preserved, 1);
    const changed = JSON.parse(originalCache);
    changed.file.document.children[0].children[0].children[0].itemSpacing = 24;
    fs.writeFileSync(cachePath, JSON.stringify(changed));
    processed = await processPrComponents({ figmaSnapshot: cachePath, catalog: catalogPath, silent: true });
    assert.strictEqual(processed.summary.updated, 1, 'Snapshot node changes invalidate source fingerprint');
    const manifestBeforeFailure = fs.readFileSync('.components-manifest.json', 'utf8');
    fs.writeFileSync(catalogPath, JSON.stringify([{ ...imported.catalog[0], nodeId: 'missing' }]));
    await assert.rejects(processPrComponents({ figmaSnapshot: cachePath, catalog: catalogPath, silent: true }), /absent/);
    assert.strictEqual(fs.readFileSync('.components-manifest.json', 'utf8'), manifestBeforeFailure);
    // Enabling snapshots alone preserves unchanged legacy/custom sources.
    const legacyDir = path.join(temp, 'legacy-workspace');
    fs.mkdirSync(legacyDir);
    process.chdir(legacyDir);
    fs.writeFileSync('components.catalog.json', JSON.stringify([{ name: 'Legacy', node: legacy, nodeId: 'legacy', fileId: fileKey }]));
    let legacyResult = await processPrComponents({ mock: true, silent: true });
    assert.strictEqual(legacyResult.summary.new, 1);
    fs.appendFileSync('components/Legacy.lite.tsx', '// caller custom edit\n');
    const legacySource = fs.readFileSync('components/Legacy.lite.tsx', 'utf8');
    legacyResult = await processPrComponents({ figmaSnapshot: cachePath, silent: true });
    assert.strictEqual(legacyResult.summary.preserved, 1);
    assert.strictEqual(fs.readFileSync('components/Legacy.lite.tsx', 'utf8'), legacySource);
    process.chdir(temp);
    const cliOut = path.join(temp, 'cli');
    execFileSync(process.execPath, [path.join(root, 'scripts/figma-to-mitosis.js'), '--figma-snapshot=' + cachePath, '--node=set', '--name=Breadcrumb', '--composition=' + path.join(root, 'scripts/fixtures/breadcrumb.composition.json'), '--out=' + cliOut], { cwd: temp, stdio: 'pipe' });
    assert(fs.existsSync(path.join(cliOut, 'BreadcrumbLink.lite.tsx')));
    console.log('Figma snapshot: one fetch/reuse, invalid input/refresh preservation, metadata, offline discovery/resolution/composition and CLI verified.');
  } finally {
    process.chdir(previousCwd);
    fs.rmSync(temp, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
